"""The HANAN kit's samples (DRUM engine, firmware/src/drum_voice.c) -> a C header.

  tools/gen_cumbia_pcm.py OUT.h

assets/samples-cumbia/ (README.md there: sources and licences): Hanan Cumbia's four at their own rate (9804 Hz, as
the Bleep Drum plays them), the TR-727 recordings at 22050 Hz. Each: the silence before its onset cut, at most
MAX_S seconds (a short fade at a cut), its peak at -6 dBFS, 8-bit mu-law (G.711). The order is the lanes':
KICK TIMBL MARAC GUIRO CABAS CONGA QUINT CAMPN (DV_KIT's HANAN row reads CPCM[v[0]]).
"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sampleio import onset, peak, read_any_wav, resample  # noqa: E402

SRC = Path(__file__).resolve().parents[1] / "assets" / "samples-cumbia"
# file, stored rate (0: its own), at most seconds
SAMPLES = [
    ("bombo-kick.wav", 0, 0.60),
    ("727-high-timbale.wav", 22050, 0.45),
    ("727-maracas.wav", 22050, 0.12),
    ("huiro-guiro.wav", 0, 0.30),
    ("727-cabasa.wav", 22050, 0.16),
    ("conga.wav", 0, 0.55),
    ("727-open-high-conga.wav", 22050, 0.18),
    ("campana-cowbell.wav", 0, 0.62),
]


def ulaw_enc(x):
    """float -1..1 -> G.711 mu-law byte"""
    s = max(-32635, min(32635, int(round(x * 32767))))
    sign = 0x80 if s < 0 else 0
    s = (-s if s < 0 else s) + 0x84
    exp = 7
    while exp > 0 and not (s & (0x4000 >> (7 - exp))):
        exp -= 1
    man = (s >> (exp + 3)) & 0x0F
    return ~(sign | (exp << 4) | man) & 0xFF


def ulaw_dec(b):
    b = ~b & 0xFF
    sign, exp, man = b & 0x80, (b >> 4) & 7, b & 0x0F
    s = (((man << 3) + 0x84) << exp) - 0x84
    return -s if sign else s


def main(out):
    data, table = [], []
    for name, rate, max_s in SAMPLES:
        sr, x = read_any_wav(SRC / name)
        if rate and rate != sr:
            x = resample(x, sr, rate)
            sr = rate
        x = x[max(0, onset(x, 0.01) - 2):]
        n = min(len(x), int(max_s * sr))
        if n < len(x):                                   # cut: a 15 ms fade
            f = min(n, int(0.015 * sr))
            for i in range(f):
                x[n - f + i] *= 1.0 - (i + 1) / f
        x = x[:n]
        m = sum(x[-max(1, n // 8):]) / max(1, n // 8)    # the 8-bit recordings sit a little off zero: take it out,
        x = [v - m for v in x]                           # then a 20 Hz high-pass for what remains, a 5 ms fade out
        a, y1, x1 = math.exp(-2 * math.pi * 20 / sr), 0.0, 0.0
        for i, v in enumerate(x):
            y1 = a * (y1 + v - x1)
            x1 = v
            x[i] = y1
        f = min(n, int(0.005 * sr))
        for i in range(f):
            x[n - f + i] *= 1.0 - (i + 1) / f
        g = 0.5 / peak(x)
        table.append((len(data), n, sr, name))
        data += [ulaw_enc(v * g) for v in x]
    lines = ["/* generated by tools/gen_cumbia_pcm.py from assets/samples-cumbia (README.md: sources, licences) */",
             "#pragma once", "#include <stdint.h>",
             f"#define CPCM_N {len(SAMPLES)}",
             "static const int16_t CPCM_ULAW[256] = {"]
    dec = [ulaw_dec(b) for b in range(256)]
    for i in range(0, 256, 16):
        lines.append("    " + ", ".join(str(v) for v in dec[i:i + 16]) + ",")
    lines.append("};")
    lines.append("static const struct { uint32_t off, len; uint16_t rate; } CPCM[CPCM_N] = {")
    for off, n, sr, name in table:
        lines.append(f"    {{{off}, {n}, {sr}}},   /* {name} */")
    lines.append("};")
    lines.append(f"static const uint8_t CPCM_DATA[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(v) for v in data[i:i + 24]) + ",")
    lines.append("};")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"cumbia pcm: {len(SAMPLES)} samples, {len(data)} B -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])

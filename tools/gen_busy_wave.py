"""ANALOG's WAVE PIBE: single-cycle tables of the Busy Boy's harmonic recipe -> firmware/engines/src/busy_wave.h

  tools/gen_busy_wave.py

tools/busy_harm.json: the 32 harmonics' levels (linear, the loudest 1) of the Korg N364 / X5D "Busy Boy", measured on
its multisample (a SoundFont of the N364's samples, 9 zones, and a demo recording agreeing within 1.5 dB) in two
registers: "low" (the zones of C3 .. C4, around 200 Hz) and "high" (C5 .. G5, around 650 Hz). The 3rd and 4th harmonics lead, the fundamental 20 dB under, the 6th and 9th hollow, the
10th up again; the high register a little brighter above the 7th. (The sound is two of these, about 8 cents apart:
the preset's DTN 8, MIX 64; measured as each harmonic's beating, 1.45 Hz times its number at 298 Hz.) Nothing of the
recording is kept: only these numbers. The tables: 256 points, the harmonics up to 32 / 16 / 8 / 4 / 2 (each
band-limited for its range of pitch: the oscillator picks the richest one whose top harmonic stays under 18 kHz),
Newman's phases (a low crest), the peak at 0.9 of full scale; the oscillator crossfades low to high between the two
registers' pitches."""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
J = json.loads((ROOT / "tools" / "busy_harm.json").read_text())
N = 256
LEVELS = [32, 16, 8, 4, 2]


def table(H, nh):
    w = [0.0] * N
    for k in range(1, nh + 1):
        a = H[k - 1]
        ph = math.pi * k * k / nh
        for i in range(N):
            w[i] += a * math.sin(2 * math.pi * k * i / N + ph)
    pk = max(abs(v) for v in w)
    return [int(round(v / pk * 0.9 * 32767)) for v in w]


lines = ["/* SPDX-License-Identifier: MIT */",
         "/* generated by tools/gen_busy_wave.py (tools/busy_harm.json): ANALOG's WAVE PIBE, 256-point single cycles",
         " * with the harmonics up to 32 / 16 / 8 / 4 / 2, the low register's and the high's */",
         "#define BUSY_N 256",
         "#define BUSY_SHIFT 24                                  /* 256 points: the phase's top 8 bits */",
         f"#define BUSY_LO_HZ {J['low_hz']}",
         f"#define BUSY_HI_HZ {J['high_hz']}",
         f"#define BUSY_LEVELS {len(LEVELS)}",
         "static const uint8_t BUSY_HARMS[BUSY_LEVELS] = {" + ", ".join(map(str, LEVELS)) + "};",
         "static const int16_t BUSY_WAVE[2][BUSY_LEVELS][BUSY_N + 1] = {"]
for reg in ("low", "high"):
    lines.append("    {   /* " + reg + " */")
    for nh in LEVELS:
        t = table(J[reg], nh)
        t.append(t[0])                                 # the guard point: linear interpolation reads one past
        lines.append("        {")
        for i in range(0, len(t), 16):
            lines.append("            " + ", ".join(str(v) for v in t[i:i + 16]) + ",")
        lines.append("        },")
    lines.append("    },")
lines.append("};")
# the decay the Korg's amp envelope makes, by key (dB a second, measured 0.3 .. 2.5 s on each zone: flat in the bass,
# about -2 at C4, -4.5 at C5, -11 at G5): per 32-sample block, Q16, for notes 0..127 (interpolated between the zones)
D = sorted((int(k), v) for k, v in J["decay_db_s"].items())
def decay_at(n):
    if n <= D[0][0]:
        return min(0.0, D[0][1]) if n >= 44 else 0.0
    for (a, va), (b, vb) in zip(D, D[1:]):
        if n <= b:
            return va + (vb - va) * (n - a) / (b - a)
    return D[-1][1] * 2 ** ((n - D[-1][0]) / 12)
lines.append("/* the Korg's decay by key: the gain kept per 32-sample block, Q16 (65536: none) */")
lines.append("static const uint16_t BUSY_DECAY[128] = {")
row = []
for n in range(128):
    k = 10 ** (decay_at(n) * 32 / 44100 / 20)
    row.append(str(min(65535, int(round(k * 65536)))))
for i in range(0, 128, 16):
    lines.append("    " + ", ".join(row[i:i + 16]) + ",")
lines.append("};")
out = ROOT / "firmware" / "engines" / "src" / "busy_wave.h"
out.write_text("\n".join(lines) + "\n")
print(f"busy wave: {len(LEVELS)} tables x {N + 1} -> {out}")
